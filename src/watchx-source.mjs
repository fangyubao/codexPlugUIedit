import { assert } from './model.mjs';

// Tokenize comments and strings to avoid rewriting examples or string literals.
export function maskCpp(text){
  return text.replace(/\/\*[\s\S]*?\*\/|\/\/[^\r\n]*|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'/g,match=>match.replace(/[^\r\n]/g,' '));
}
export function matching(text,start,open='(',close=')'){
  let depth=0;for(let i=start;i<text.length;i++){if(text[i]===open)depth++;if(text[i]===close&&--depth===0)return i;}throw new Error('C++ 代码括号不完整');
}
export function createSites(text){
  const masked=maskCpp(text),sites=[];
  for(const m of masked.matchAll(/\blv_(?:obj|cont|label|img|led|btn|slider|bar|cb|ta|arc|line|chart|table|win)_create\s*\(/g)){
    const start=m.index,open=masked.indexOf('(',start),end=matching(masked,open);
    const before=masked.slice(Math.max(0,start-160),start);
    const variable=before.match(/([A-Za-z_]\w*(?:\s*\[[^\]]+\])?)\s*=\s*$/)?.[1]?.replaceAll(/\s/g,'')||m[0].split('(')[0].trim();
    sites.push({start,end,line:text.slice(0,start).split('\n').length,variable});
  }
  return sites;
}
export function instrumentCreates(text,filename,mode='host'){
  const sites=createSites(text);
  for(const site of sites.reverse()){
    const expr=text.slice(site.start,site.end+1);
    const replacement=mode==='host'?`studio_tag(${expr}, ${JSON.stringify(filename)}, ${site.line})`:`ui_studio_${mode}::capture(${expr}, ${site.line})`;
    text=text.slice(0,site.start)+replacement+text.slice(site.end+1);
  }
  return text;
}
export function patchPageSource(original,page){
  const begin=`// UI_STUDIO_${page}_BEGIN`,end=`// UI_STUDIO_${page}_END`;
  assert(!original.includes(begin),'该页面已接入 UI Studio；不应再次插入接入代码');
  let text=instrumentCreates(original,'',page);
  const masked=maskCpp(text),match=/\bstatic\s+void\s+Setup\s*\(\s*\)\s*\{/.exec(masked);assert(match,'未找到页面 Setup');
  const open=masked.indexOf('{',match.index),close=matching(masked,open,'{','}');
  text=text.slice(0,close)+`\n    ui_studio_${page}::apply();\n`+text.slice(close);
  text=text.slice(0,open+1)+`\n    ui_studio_${page}::reset();\n`+text.slice(open+1);
  return `${begin}\n#include "../UIStudioGenerated/${page}.h"\n${end}\n`+text;
}
export function firmwareHeader(page,edits){
  const sites=[...new Set(edits.map(e=>e.site))];
  const capacity=Math.max(1,sites.reduce((sum,site)=>sum+1+Math.max(...edits.filter(e=>e.site===site).map(e=>e.instance)),0));
  const limits=sites.map(site=>`case ${site}: limit=${1+Math.max(...edits.filter(e=>e.site===site).map(e=>e.instance))}; break;`).join(' ');
  const lines=[`// Generated by UI Studio for WatchX / LVGL 6.1.2.`,`#pragma once`,`#include "lvgl/lvgl.h"`,`namespace ui_studio_${page} {`,
    'struct Entry { lv_obj_t *obj; int site; int index; };',
    `static Entry entries[${capacity}]; static unsigned count = 0;`,
    'static void reset() { count = 0; }',
    `static lv_obj_t *capture(lv_obj_t *obj, int site) { int limit=0; switch(site) { ${limits} default: return obj; } int index = 0; for(unsigned i=0;i<count;i++) if(entries[i].site==site) index++; if(index<limit && count<${capacity}) { entries[count].obj=obj; entries[count].site=site; entries[count].index=index; count++; } return obj; }`,
    'static lv_obj_t *find(int site,int index){for(unsigned i=0;i<count;i++) if(entries[i].site==site && entries[i].index==index) return entries[i].obj; return 0;}',
    'static void apply() {',
  ];
  let styleCount=0;
  for(const edit of edits){
    const {site,instance,changes}=edit;assert(Number.isInteger(site)&&Number.isInteger(instance),'无效源码位置');
    lines.push(`    if(lv_obj_t *obj = find(${site}, ${instance})) {`);
    if('text'in changes)lines.push(`        lv_label_set_text(obj, "${[...Buffer.from(changes.text,'utf8')].map(b=>'\\'+b.toString(8).padStart(3,'0')).join('')}");`);
    if('x'in changes||'y'in changes)lines.push('        lv_obj_set_auto_realign(obj, false);');
    for(const[key,fn]of [['width','width'],['height','height'],['x','x'],['y','y']])if(key in changes)lines.push(`        lv_obj_set_${fn}(obj, ${Math.round(changes[key])});`);
    if('visible'in changes)lines.push(`        lv_obj_set_hidden(obj, ${!changes.visible});`);
    if(['color','background','border','radius'].some(k=>k in changes)){
      const name=`style_${styleCount++}`;lines.push(`        static lv_style_t ${name}; ${name} = *lv_obj_get_style(obj);`);
      for(const[key,field]of [['color','text.color'],['background','body.main_color'],['border','body.border.color']])if(key in changes)lines.push(`        ${name}.${field} = lv_color_hex(0x${changes[key].slice(1)});`);
      if('background'in changes)lines.push(`        ${name}.body.grad_color = ${name}.body.main_color;`);
      if('radius'in changes)lines.push(`        ${name}.body.radius = ${Math.round(changes.radius)};`);
      lines.push(`        lv_obj_set_style(obj, &${name});`);
    }
    lines.push('    }');
  }
  lines.push('}','}', '');return lines.join('\n');
}
